// ===== ข้อมูลแฟชั่น: ปีก / หาง / สัตว์เลี้ยง (อย่างละ 30 แบบ) =====
// รูปอยู่ที่ assets/fashion/ : wing_01_front.png, wing_01_back.png, tail_01.png, pet_01.png (01-30)
// สูตรสร้าง/โบนัสสถานะ อยู่ใน js/systems/fashionCraft.js (ไฟล์นี้เก็บแค่ชื่อ/ระดับ/ไฟล์รูป)
// ระดับ (tier): 1 ธรรมดา (01-10) | 2 หายาก (11-20) | 3 เอพิค (21-26) | 4 ตำนาน (27-30)
(function () {
  var TIER_NAME = { 1: 'ธรรมดา', 2: 'หายาก', 3: 'เอพิค', 4: 'ตำนาน' };

  // ตำแหน่ง/ขนาดเริ่มต้น (ปรับตอนทดสอบ) : x,y = ชดเชยจากกลางตัวละคร, scale = ขนาด
  var DEFAULT_LOOK = {
    wing: { x: 0,   y: -6, scale: 0.40 },   // ภาพ 256 -> ~100px
    tail: { x: -14, y: 10, scale: 0.28 },   // ภาพ 192 -> ~54px
    pet:  { x: -38, y: 14, scale: 0.30 }    // ภาพ 384x128 (3 มุมมอง) ตัดเป็นช่องละ 128
  };

  var NAMES = {
    wing: ['ปีกนางฟ้า','ปีกกา','ปีกผีเสื้อชมพู','ปีกแมลงปอ','ปีกค้างคาวม่วง','ปีกหงส์เพลิง','ปีกผลึกน้ำแข็ง','ปีกอสุนี','ปีกใบหยก','ปีกทองจักรพรรดิ',
           'ปีกกลีบบัว','ปีกจันทรา','ปีกสุริยัน','ปีกซากุระ','ปีกกาแล็กซี','ปีกกลไก','ปีกอสูร','ปีกเกล็ดมังกร','ปีกแมงกะพรุนวิญญาณ','ปีกเมฆา',
           'ปีกนกยูง','ปีกเทพกา','ปีกกระจกสี','ปีกกุหลาบหนาม','ปีกขนมหวาน','ปีกสายรุ้ง','ปีกกระดูกวิญญาณ','ปีกนีออน','ปีกแพรสวรรค์','ปีกเก้าสวรรค์'],
    tail: ['หางจิ้งจอก','หางจิ้งจอกเก้าหาง','หางแมวดำ','หางสุนัขทอง','หางหมาป่า','หางกระรอก','หางกระต่าย','หางมังกรเขียว','หางปีศาจ','หางจิ้งเหลน',
           'หางนางเงือก','หางนกยูง','หางหงส์เพลิง','หางน้ำแข็ง','หางสายฟ้า','หางเสือดาว','หางเสือ','หางแรคคูน','หางแมงป่อง','หางค้างคาว',
           'หางยูนิคอร์น','หางแพรริบบิ้น','หางอเมทิสต์','หางหยกแกะสลัก','หางดอกบัว','หางเมฆ','หางเงามืด','หางทองคำ','หางดาราจักร','หางกิเลน'],
    pet:  ['ลูกเจี๊ยบ','ลูกแมวขาว','ลูกชิบะ','กระต่ายหูตก','แฮมสเตอร์','แพนด้าแดง','ลูกจิ้งจอก','มังกรน้อย','สไลม์ฟ้า','ลูกนกกระเรียน',
           'เต่าเจดีย์','นกฮูกขาว','แพนด้าน้อย','ลูกเสือ','ลูกหมาป่า','ลูกหงส์เพลิง','ลูกกิเลน','ปลาคาร์ฟในฟอง','วิญญาณผีเสื้อ','โคมผี',
           'กระต่ายหยก','ลูกนกสายฟ้า','กบใบบัว','เห็ดน้อย','ซาลาเปามีชีวิต','จิ้งจอกน้ำแข็ง','แมวเงา','หมูทองนำโชค','ลูกกิเลนขาว','กระเรียนสวรรค์']
  };

  function tierOf(n) { return n <= 10 ? 1 : n <= 20 ? 2 : n <= 26 ? 3 : 4; }
  function pad(n) { return (n < 10 ? '0' : '') + n; }

  var ITEMS = {};
  ['wing', 'tail', 'pet'].forEach(function (type) {
    NAMES[type].forEach(function (name, i) {
      var n = i + 1, id = type + '_' + pad(n), t = tierOf(n);
      ITEMS[id] = {
        id: id, type: type, name: name, tier: t,
        n: n,
        look: DEFAULT_LOOK[type],
        img: type === 'wing'
          ? { front: 'assets/fashion/' + id + '_front.png', back: 'assets/fashion/' + id + '_back.png' }
          : { main: 'assets/fashion/' + id + '.png' }
      };
    });
  });

  window.FashionData = {
    ITEMS: ITEMS,
    TIER_NAME: TIER_NAME,
    list: function (type) {
      return Object.keys(ITEMS).filter(function (k) { return ITEMS[k].type === type; }).map(function (k) { return ITEMS[k]; });
    },
  };
})();
